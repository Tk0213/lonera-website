def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "design-system"))
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the bundle on disk is stale")
    a = ap.parse_args()

    css = style_block(io.open(APP, encoding="utf-8").read())
    imgs = {k: photo(k + ".jpg") for k in ("home", "clean", "clinic")}
    cards = build(css, imgs)

    stale = []
    for path, html in cards.items():
        full = os.path.join(a.out, path)
        old = io.open(full, encoding="utf-8").read() if os.path.exists(full) else None
        if old != html:
            stale.append(path)
        if not a.check:
            os.makedirs(os.path.dirname(full), exist_ok=True)
            io.open(full, "w", encoding="utf-8").write(html)

    if a.check:
        if stale:
            print("design system is stale (%d): %s" % (len(stale), ", ".join(sorted(stale))))
            return 1
        print("design system is current (%d cards)" % len(cards))
        return 0

    print("wrote %d cards to %s" % (len(cards), a.out))
    if stale:
        print("changed: " + ", ".join(sorted(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
