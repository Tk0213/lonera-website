# ---------------------------------------------------------------- css parsing
def style_block(html):
    """The first <style> block: the app's own stylesheet.

    The second one holds the base64 photographs and is deliberately skipped -
    a component library should show the component, not ship a photo library.
    """
    a = html.index("<style>") + len("<style>")
    return html[a : html.index("</style>", a)]


def top_level_rules(css):
    """Yield (selector, body) for each top-level rule.

    Brace-counting rather than a regex, because the sheet contains @media,
    @supports and @keyframes blocks whose nested rules must not be mistaken
    for top-level ones.
    """
    out, i, n = [], 0, len(css)
    while i < n:
        b = css.find("{", i)
        if b == -1:
            break
        # a top-level statement such as `@import url(...);` sits in front of the
        # next selector, so keep only what follows the last `;`
        sel = css[i:b].split(";")[-1].strip()
        depth, j = 1, b + 1
        while j < n and depth:
            if css[j] == "{":
                depth += 1
            elif css[j] == "}":
                depth -= 1
            j += 1
        body = css[b + 1 : j - 1]
        if sel and not sel.startswith("@"):
            out.append((sel, body.strip()))
        i = j
    return out


def rules_for(css, wanted):
    """Every top-level rule whose selector list touches one of `wanted`.

    Matches on the bare class token so `.pw` picks up `.pw::after` and
    `.poster:hover .pw`, but never `.pwx`.
    """
    keep = []
    for sel, body in top_level_rules(css):
        parts = [p.strip() for p in sel.split(",")]
        hit = False
        for p in parts:
            for w in wanted:
                if re.search(r"(?<![\w-])" + re.escape(w) + r"(?![\w-])", p):
                    hit = True
                    break
            if hit:
                break
        if hit:
            keep.append(sel + "{" + body + "}")
    return "\n".join(keep)


def tokens(css):
    for sel, body in top_level_rules(css):
        if sel == ":root":
            return ":root{" + body + "}"
    raise SystemExit("no :root token block found in app-preview.html")


